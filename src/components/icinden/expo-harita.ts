export const OSM_ATIF = "© OpenStreetMap katkıda bulunanlar" as const;

/** [x, y] metre; x doğu+, y güney+ (SVG). */
export type Nokta = readonly [x: number, y: number];
/** Açık çoklu çizgi (yol, pist, kıyı). */
export type Cizgi = readonly Nokta[];
/** Poligon dış halkası; ilk nokta sonda tekrarlanmaz. */
export type Halka = readonly Nokta[];
/** SVG viewBox ile aynı düzen: sol-üst köşe + genişlik/yükseklik (metre). */
export type Kutu = { readonly x: number; readonly y: number; readonly w: number; readonly h: number };
/** Kutunun coğrafi karşılığı (derece). */
export type CografiKutu = {
  readonly guney: number;
  readonly bati: number;
  readonly kuzey: number;
  readonly dogu: number;
};
export type YolKademesi = "ana" | "ikincil" | "servis";

export type ExpoHarita = {
  /** Orijinin coğrafi konumu (Expo poligonunun alan ağırlık merkezi). */
  readonly merkez: { readonly lat: number; readonly lng: number };
  /** Ayrıntı penceresi: yollar bu ±900 m kutuya kırpıldı. */
  readonly bbox: Kutu & CografiKutu;
  /** Antalya Expo Center sınırı (OSM way 1572443333). */
  readonly expo: Halka;
  /** Expo içindeki/bitişik binalar (OSM'de tek bina: bütünleşik fuar holü). */
  readonly salonlar: readonly Halka[];
  /** ±700 m içindeki diğer binalar (seralar dahil), DP 3 m. */
  readonly binalar: readonly Halka[];
  /** Yollar, 3 kademe, ±900 m'ye kırpılmış, DP 4 m. */
  readonly yollar: { readonly [K in YolKademesi]: readonly Cizgi[] };
  /** Havalimanı pistleri + taksi yolları (orta çizgi; KIRPILMADI, Expo'nun 2,5–6,5 km GB'si). */
  readonly pist: readonly Cizgi[];
  /** pist'in ilk 3 öğesi: yalnızca iniş-kalkış pistleri (genişlik 45 m). */
  readonly pistAna: readonly Cizgi[];
  /** Su yüzeyleri (natural=water). */
  readonly su: readonly Halka[];
  /** Antalya Körfezi kıyı çizgisi (natural=coastline), kiyiBbox'a kırpılmış, DP 60 m. */
  readonly kiyi: readonly Cizgi[];
  /**
   * Deniz alanı: [0] kıyı + kiyiBbox kenarıyla kapatılmış deniz poligonu, sonrakiler adalar.
   * fill-rule="evenodd" ile çiz (adalar delik olur). Kıyı çekilemediyse boş.
   */
  readonly deniz: readonly Halka[];
  readonly kiyiBbox: Kutu & CografiKutu;
  readonly pistBbox: Kutu;
  readonly atif: typeof OSM_ATIF;
};

/** Coğrafi → yerel metre (aynı projeksiyon). Yeni işaretçi eklemek için. */
export const METRE_DERECE = { x: 88874.6981, y: 111195.0802 } as const;

export function konum(lat: number, lng: number): Nokta {
  return [
    Math.round((lng - 30.8175767) * METRE_DERECE.x),
    Math.round((36.9397171 - lat) * METRE_DERECE.y),
  ];
}

/** Açık çizgi → SVG path "d" ("M x y L x y …"). */
export function yolPath(seg: readonly (readonly number[])[]): string {
  let d = "";
  for (let i = 0; i < seg.length; i++) d += (i === 0 ? "M" : "L") + seg[i][0] + " " + seg[i][1];
  return d;
}

/** Halka → kapalı SVG path "d". */
export function alanPath(ring: readonly (readonly number[])[]): string {
  return ring.length ? yolPath(ring) + "Z" : "";
}

/** Birçok parçayı tek path'te birleştirir (tek <path> = az DOM düğümü). */
export function birlesikPath(parcalar: readonly (readonly (readonly number[])[])[], kapali = false): string {
  let d = "";
  for (const p of parcalar) d += kapali ? alanPath(p) : yolPath(p);
  return d;
}

